package com.mantz_it.rfanalyzer.addon.rds

import com.mantz_it.rfanalyzer.addon.fm.DecimatingComplexFir
import com.mantz_it.rfanalyzer.addon.fm.DspUtil
import com.mantz_it.rfanalyzer.addon.fm.SinCosTable
import kotlin.math.PI
import kotlin.math.abs
import kotlin.math.floor
import kotlin.math.sqrt

/**
 * <h1>RF Analyzer - RDS demodulator</h1>
 *
 * Module:      RdsDemodulator.kt
 * Description: MPX (192 kHz, see MpxDemodulator) to RDS data bits (1187.5 bit/s):
 *              57 kHz mix-down, two-stage low-pass decimation to 12 kHz, Costas loop for the
 *              BPSK carrier phase, biphase matched filter, early-late gate symbol timing recovery with
 *              linear interpolation, and differential decoding. Bits go to [onBit].
 *
 * The 57 kHz subcarrier is generated by the transmitter, so its frequency only carries the
 * receiver's sample clock error (a few Hz at most) - the Costas loop tracks that.
 *
 * Part of Richard's personal RF Analyzer fork (local decoders replacing the closed extension).
 * License: http://www.gnu.org/licenses/gpl.html GPL version 2 or higher
 */
class RdsDemodulator(
    private val inputRate: Int = 192_000,
    private val onBit: (Int) -> Unit,
) {
    companion object {
        const val BIT_RATE = 1187.5
        const val SUBCARRIER_HZ = 57_000.0
        private const val STAGE1_DECIMATION = 8   // 192 k -> 24 k
        private const val STAGE2_DECIMATION = 2   // 24 k -> 12 k
    }

    private val rate1 = inputRate.toDouble() / STAGE1_DECIMATION
    private val rate2 = rate1 / STAGE2_DECIMATION
    private val sps = rate2 / BIT_RATE                  // ≈10.105 samples per bit

    // mixer (cycles)
    private var mixPhase = 0.0
    private val mixStep = SUBCARRIER_HZ / inputRate

    // stage 1: cutoff 4 kHz, must be quiet from 20 kHz (aliases into 0..4 kHz at 24 kHz)
    private val fir1 = DecimatingComplexFir(DspUtil.lowPassTaps(63, inputRate.toDouble(), 6_000.0), STAGE1_DECIMATION)
    // stage 2: the RDS band is ±2.4 kHz, the L-R band ends 4 kHz below 57 kHz
    private val fir2 = DecimatingComplexFir(DspUtil.lowPassTaps(97, rate1, 2_900.0), STAGE2_DECIMATION)

    // Costas loop (cycles)
    private var costasPhase = 0.0
    private var costasFreq = 0.0
    private val costasKp: Double
    private val costasKi: Double
    private var powerAvg = 1e-6f

    // biphase matched filter over one bit: + first half, - second half
    private val mfLen = Math.round(sps).toInt()          // 10
    private val mfHist = FloatArray(mfLen)
    private var mfPos = 0

    // matched-filter output history for interpolation (ring)
    private val ringSize = 64
    private val ring = FloatArray(ringSize)
    private var sampleIndex = 0L                          // index of the newest sample in ring

    // timing recovery
    private var nextSampleTime = sps                     // in units of samples (absolute)
    private var lastSymbol = 0f
    private var symbolPowerAvg = 1e-6f
    private val timingGain = 0.02
    private var absSym = 0f
    private var absMid = 0f
    private var halfCheck = 0

    // differential decoding
    private var lastDecision = 0

    /** Diagnostics: every symbol decision value (in-phase) and the quadrature at that instant. */
    var symbolListener: ((i: Float, q: Float) -> Unit)? = null

    /** Average carrier amplitude after the mixer (MPX units), for the RDS injection level. */
    @Volatile var carrierLevel = 0f
        private set
    /** Mean |error| of the Costas loop: low = locked carrier. */
    @Volatile var costasLock = 0f
        private set

    init {
        val wn = 2 * PI * 8.0 / rate2
        costasKp = 2 * 0.707 * wn / (2 * PI)
        costasKi = wn * wn / (2 * PI)
    }

    fun reset() {
        mixPhase = 0.0; costasPhase = 0.0; costasFreq = 0.0; powerAvg = 1e-6f
        fir1.reset(); fir2.reset()
        mfHist.fill(0f); mfPos = 0; ring.fill(0f); sampleIndex = 0
        nextSampleTime = sps; lastSymbol = 0f; absSym = 0f; absMid = 0f; halfCheck = 0; symbolPowerAvg = 1e-6f; lastDecision = 0
        carrierLevel = 0f; costasLock = 0f
    }

    fun process(mpx: FloatArray, n: Int) {
        var phase = mixPhase
        for (i in 0 until n) {
            val x = mpx[i]
            val re = x * SinCosTable.cos(phase)
            val im = -x * SinCosTable.sin(phase)
            phase += mixStep
            if (phase >= 1.0) phase -= 1.0
            if (fir1.push(re, im)) {
                if (fir2.push(fir1.outRe, fir1.outIm)) {
                    processBaseband(fir2.outRe * 2, fir2.outIm * 2)
                }
            }
        }
        mixPhase = phase
    }

    private var lockAcc = 0f
    private var levelAcc = 0f
    private var statCount = 0

    private fun processBaseband(zr: Float, zi: Float) {
        // Costas loop: rotate by e^{-jφ}
        val c = SinCosTable.cos(costasPhase)
        val s = SinCosTable.sin(costasPhase)
        val vr = zr * c + zi * s
        val vi = zi * c - zr * s
        val p = vr * vr + vi * vi
        powerAvg += 0.001f * (p - powerAvg)
        val err = (vr * vi) / (powerAvg + 1e-12f)   // BPSK, independent of the data sign
        val e = err.coerceIn(-1f, 1f).toDouble()
        costasFreq += costasKi * e
        costasFreq = costasFreq.coerceIn(-10.0 / rate2, 10.0 / rate2)
        costasPhase += costasFreq + costasKp * e
        costasPhase -= floor(costasPhase)

        lockAcc += abs(e.toFloat()); levelAcc += sqrt(p); statCount++
        if (statCount >= 1200) {
            costasLock = lockAcc / statCount; carrierLevel = levelAcc / statCount
            lockAcc = 0f; levelAcc = 0f; statCount = 0
        }

        // biphase matched filter on the in-phase part
        mfHist[mfPos] = vr
        mfPos = (mfPos + 1) % mfLen
        var acc = 0f
        val half = mfLen / 2
        for (k in 0 until mfLen) {
            val v = mfHist[(mfPos + k) % mfLen]             // oldest first
            acc += if (k < half) v else -v
        }
        sampleIndex++
        ring[(sampleIndex % ringSize).toInt()] = acc

        // Gardner timing recovery
        val delta = sps / 4
        while (nextSampleTime + delta <= sampleIndex - 1) {
            val y = interpolate(nextSampleTime)
            val yMid = interpolate(nextSampleTime - sps / 2)
            // early-late gate on the matched filter's magnitude
            val yEarly = interpolate(nextSampleTime - delta)
            val yLate = interpolate(nextSampleTime + delta)
            symbolPowerAvg += 0.01f * (abs(y) - symbolPowerAvg)
            val te = (abs(yLate) - abs(yEarly)) / (symbolPowerAvg + 1e-12f)
            nextSampleTime += sps + timingGain * te.coerceIn(-1f, 1f)
            lastSymbol = y
            // Biphase has a second stable Gardner point half a bit off, where the matched filter
            // gives ±1 only on data transitions. Compare the eye at the symbol and mid points and
            // jump half a bit when the mid point is the more open one.
            absSym += abs(y); absMid += abs(yMid); halfCheck++
            if (halfCheck >= 64) {
                if (absMid > 1.3f * absSym) nextSampleTime += sps / 2
                absSym = 0f; absMid = 0f; halfCheck = 0
            }
            symbolListener?.invoke(y, 0f)
            val decision = if (y >= 0) 1 else 0
            onBit(decision xor lastDecision)
            lastDecision = decision
        }
    }

    private fun interpolate(t: Double): Float {
        val i0 = floor(t).toLong()
        val frac = (t - i0).toFloat()
        if (sampleIndex - i0 >= ringSize - 1 || i0 < 0) return 0f
        val a = ring[(i0 % ringSize).toInt()]
        val b = ring[((i0 + 1) % ringSize).toInt()]
        return a + (b - a) * frac
    }
}
